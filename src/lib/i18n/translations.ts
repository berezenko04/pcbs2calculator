export function useT(lang: Lang) {
  return (key: string, ...args: string[]): string => {
    const entry = t[lang]?.[key]
    if (typeof entry === 'function') return entry(...args)
    return entry ?? t.en[key] ?? key
  }
}

export type TFunction = ReturnType<typeof useT>
